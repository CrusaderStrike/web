// web#38 change-detection tests for tools/guild-pages-hash.js. Run: node tests/guild-pages-hash.test.js
const fs = require('fs'); const os = require('os'); const path = require('path');
const H = require('../tools/guild-pages-hash.js');
const B = require('../tools/build-guild-pages.js');
let n = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); n++; if (!c) process.exitCode = 1; };
const tmp = () => fs.mkdtempSync(path.join(os.tmpdir(), 'csh-'));
const res = (status, body) => () => Promise.resolve({ ok: status === 200, text: () => Promise.resolve(body) });
(async () => {
  const now = Date.parse('2026-11-04T12:00:00Z');
  const a = tmp(), b = tmp();
  await B.build({ out: a, src: B.mockSource(), source: 'api', now });
  await B.build({ out: b, src: B.mockSource(), source: 'api', now });
  const ha = H.hashOutput(a), hb = H.hashOutput(b);
  ok(/^[0-9a-f]{64}$/.test(ha.hash) && ha.files > 3, 'hash is sha256 over generated files');
  ok(ha.hash === hb.hash, 'same data => same hash (deterministic)');
  fs.writeFileSync(path.join(b, 'robots.txt'), 'x'); fs.writeFileSync(path.join(b, 'index.html'), 'x');
  ok(H.hashOutput(b).hash === ha.hash, 'files outside g/, guilds/, sitemap.xml ignored');
  H.writeManifest(b, H.hashOutput(b));
  ok(H.hashOutput(b).hash === ha.hash, 'manifest itself not hashed');
  ok(JSON.parse(fs.readFileSync(path.join(b, H.MANIFEST), 'utf8')).hash === ha.hash, 'manifest written with hash');
  const f = path.join(b, 'g/us/emberfall/knights-of-the-silver-hand/index.html');
  fs.appendFileSync(f, ' '); ok(H.hashOutput(b).hash !== ha.hash, 'guild page edit changes hash');
  const c = tmp(); await B.build({ out: c, src: B.mockSource(), source: 'api', now });
  fs.appendFileSync(path.join(c, 'sitemap.xml'), '\n'); ok(H.hashOutput(c).hash !== ha.hash, 'sitemap edit changes hash');
  const d = tmp(); await B.build({ out: d, src: B.mockSource(), source: 'api', now });
  fs.mkdirSync(path.join(d, 'g/us/x/y'), { recursive: true }); fs.writeFileSync(path.join(d, 'g/us/x/y/index.html'), '');
  ok(H.hashOutput(d).hash !== ha.hash, 'added (even empty) page changes hash');
  ok(H.decide(ha.hash, JSON.stringify({ hash: ha.hash })) === false, 'decide: matching manifest => unchanged');
  ok(H.decide(ha.hash, JSON.stringify({ hash: 'f'.repeat(64) })) === true, 'decide: different hash => changed');
  ok(H.decide(ha.hash, '<html>404</html>') === true && H.decide(ha.hash, '{}') === true, 'decide: bad/missing manifest => changed');
  const log = console.log; console.log = () => {};
  const m1 = await H.main(['--out=' + a, '--compare-url=u'], res(200, JSON.stringify({ hash: ha.hash })));
  const m2 = await H.main(['--out=' + a, '--compare-url=u'], res(404, ''));
  const m3 = await H.main(['--out=' + a, '--compare-url=u'], () => Promise.reject(new Error('net')));
  const m4 = await H.main(['--out=' + a]);
  const go = path.join(tmp(), 'out'); process.env.GITHUB_OUTPUT = go;
  await H.main(['--out=' + a, '--compare-url=u'], res(200, JSON.stringify({ hash: ha.hash }))); delete process.env.GITHUB_OUTPUT;
  console.log = log;
  ok(m1.changed === false, 'main: live manifest matches => changed=false');
  ok(m2.changed === true && m3.changed === true, 'main: 404 or network error => changed=true (deploy)');
  ok(m4.changed === true, 'main: no compare url (push/manual) => changed=true');
  ok(fs.readFileSync(go, 'utf8') === 'changed=false\nhash=' + ha.hash + '\n', 'GITHUB_OUTPUT gets changed + hash');
  const wfp = path.join(__dirname, '../.github/workflows/deploy-pages.yml');
  const wf = fs.existsSync(wfp) ? fs.readFileSync(wfp, 'utf8') : '';
  if (/guild-pages-hash/.test(wf)) {
  ok(/workflow_dispatch:/.test(wf) && /schedule:/.test(wf) && /push:/.test(wf), 'workflow: push, schedule, manual triggers');
  ok((wf.match(/if: steps\.detect\.outputs\.changed == 'true'/g) || []).length === 3 && /event_name }}" = "schedule"/.test(wf), 'workflow: deploy steps gated, compare only on schedule');
  } else console.log('SKIP workflow checks (workflow not in this tree)');
  console.log(n + ' checks');
})().catch(e => { console.error(e); process.exit(1); });
